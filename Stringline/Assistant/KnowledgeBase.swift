    static func tokens(_ text: String) -> [String] {
        let lowered = text.lowercased().replacingOccurrences(of: "’", with: "'")
        let words = lowered.split { !($0.isLetter || $0.isNumber || $0 == "'") }.map(String.init)
        let stop: Set<String> = ["a", "an", "the", "i", "do", "how", "to", "my", "of", "in", "on", "for", "is", "it", "can", "and", "or", "with",
                                 "what", "this", "that", "me", "you", "your", "be", "are", "does", "at", "from", "up", "get", "want", "need", "i'm", "it's"]
        return words.filter { !stop.contains($0) && $0.count > 1 }.map(stem)
    }

    static func stem(_ word: String) -> String {
        var w = word
        for suffix in ["ing", "ed", "es", "s"] where w.count > suffix.count + 2 && w.hasSuffix(suffix) {
            w.removeLast(suffix.count)
            break
        }
        return w
    }

    /// Best matching articles first.
    static func search(_ query: String, limit: Int = 4) -> [HelpArticle] {
        let base = tokens(query)
        guard !base.isEmpty else { return [] }
        var terms = Set(base)
        for word in base { for s in synonyms[word] ?? [] { terms.formUnion(tokens(s)) } }
        let phrase = query.lowercased()
        let scored: [(HelpArticle, Double)] = articles.map { a in
            let title = Set(tokens(a.title))
            let keys = Set(a.keywords.flatMap(tokens))
            let summary = Set(tokens(a.summary))
            let body = Set(a.steps.flatMap(tokens))
            var score = 0.0
            for t in terms {
                let weight = base.contains(t) ? 1.0 : 0.5
                if title.contains(t) { score += 3 * weight }
                if keys.contains(t) { score += 2.5 * weight }
                if summary.contains(t) { score += 1 * weight }
                if body.contains(t) { score += 0.4 * weight }
            }
            for keyword in a.keywords where keyword.contains(" ") && phrase.contains(keyword) { score += 4 }
            return (a, score)
        }
        return scored.filter { $0.1 >= 2 }.sorted { $0.1 > $1.1 }.prefix(limit).map(\.0)
    }

    /// Articles about the screen with this key (e.g. "job:estimate", "schedule").
    static func articles(forScreen key: String) -> [HelpArticle] {
        articles.filter { $0.screen == key }
    }

    static func json(_ a: HelpArticle, full: Bool) -> JSONValue {
        var o: [String: JSONValue] = ["id": .string(a.id), "title": .string(a.title), "area": .string(a.area), "summary": .string(a.summary)]
        if full {
            o["steps"] = .array(a.steps.map { .string($0) })
            o["tips"] = .array(a.tips.map { .string($0) })
            o["take_me_there"] = .from(a.screen)
            o["show_me_spots"] = .array(a.spots.compactMap { id in spot(id).map { ["id": .string($0.id), "what": .string($0.label)] } })
        }
        return .object(o)
    }
