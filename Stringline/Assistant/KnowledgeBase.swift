import Foundation

/// A how-to article the assistant answers from. Steps use the app's exact button and menu names.
struct HelpArticle: Identifiable, Hashable {
    let id: String
    let title: String
    let area: String
    let keywords: [String]
    let summary: String
    let steps: [String]
    var tips: [String] = []
    /// Where "Take me there" goes: today, pipeline, measure, jobs, schedule, customers, invoices, learn,
    /// settings:<section>, or job:<tab> (needs a job).
    var screen: String?
    /// Places on screen this article is about (HelpSpot ids), for "show me".
    var spots: [String] = []
}

/// A place on screen the assistant can point at with a pulsing ring.
struct HelpSpot: Hashable {
    enum Place: Hashable {
        case always              // the sidebar, visible on every screen
        case screen(String)      // today, pipeline, measure, jobs, schedule, customers, invoices, learn
        case jobTab(String)      // a tab of an open job: overview, measure, estimate, schedule, logs, photos, invoice
        case settings(String)    // a Settings section
        case assistant           // the assistant panel (open while the assistant is answering)
    }
    let id: String
    let label: String
    let place: Place
}

